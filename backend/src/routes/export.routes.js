import { Router } from 'express';
import prisma from '../lib/prisma.js';
import { auth } from '../middleware/auth.js';
import { adminOnly } from '../middleware/roles.js';
import { logActivity } from '../lib/utils.js';

const router = Router();

/** Full JSON backup of all system data (admin only, logged). */
router.get('/full', auth, adminOnly, async (req, res, next) => {
  try {
    const tables = {
      users: await prisma.user.findMany({ select: { id: true, name: true, email: true, role: true, active: true, createdAt: true } }),
      workers: await prisma.worker.findMany(),
      skills: await prisma.skill.findMany(),
      workerSkills: await prisma.workerSkill.findMany(),
      products: await prisma.product.findMany(),
      productDocuments: await prisma.productDocument.findMany(),
      visions: await prisma.vision.findMany(),
      roadmaps: await prisma.roadmap.findMany(),
      tasks: await prisma.task.findMany(),
      taskDependencies: await prisma.taskDependency.findMany(),
      assignments: await prisma.assignment.findMany(),
      submissions: await prisma.submission.findMany(),
      evaluations: await prisma.evaluation.findMany(),
      revisions: await prisma.revision.findMany(),
      appeals: await prisma.appeal.findMany(),
      notifications: await prisma.notification.findMany(),
      activityLogs: await prisma.activityLog.findMany(),
      aiDecisions: await prisma.aiDecision.findMany(),
      learningAdjustments: await prisma.learningAdjustment.findMany(),
      apiUsageLogs: await prisma.apiUsageLog.findMany(),
      taskTemplates: await prisma.taskTemplate.findMany(),
      digests: await prisma.digest.findMany(),
    };

    await logActivity(req.user.id, 'export.full');
    res.setHeader('Content-Disposition', `attachment; filename=task-manager-backup-${Date.now()}.json`);
    res.setHeader('Content-Type', 'application/json');
    res.send(JSON.stringify({ exportedAt: new Date().toISOString(), ...tables }, null, 2));
  } catch (e) { next(e); }
});

/** Escape a value for CSV output. */
function csvCell(v) {
  if (v === null || v === undefined) return '';
  const s = typeof v === 'object' ? JSON.stringify(v) : String(v);
  return `"${s.replace(/"/g, '""')}"`;
}

function sendCsv(res, filename, headers, rows) {
  const esc = headers.map((h) => csvCell(h)).join(',');
  const lines = rows.map((r) => headers.map((h) => csvCell(r[h] ?? '')).join(','));
  res.setHeader('Content-Type', 'text/csv; charset=utf-8');
  res.setHeader('Content-Disposition', `attachment; filename=${filename}-${Date.now()}.csv`);
  res.send([esc, ...lines].join('\n'));
}

/** CSV export: tasks with assignment + score detail. */
router.get('/tasks.csv', auth, adminOnly, async (req, res, next) => {
  try {
    const tasks = await prisma.task.findMany({
      include: {
        assignments: { where: { active: true }, include: { worker: { include: { user: { select: { name: true } } } } } },
        submissions: { include: { evaluations: { orderBy: { evaluatedAt: 'desc' }, take: 1 } } },
      },
      orderBy: { createdAt: 'desc' },
    });
    const rows = tasks.map((t) => {
      const activeAssign = t.assignments[0];
      const lastEval = t.submissions?.[0]?.evaluations?.[0];
      return {
        id: t.id,
        title: t.title,
        status: t.status,
        priority: t.priority,
        effortHours: t.effortHours,
        deadline: t.deadline ? t.deadline.toISOString() : '',
        assignedTo: activeAssign?.worker?.user?.name || '',
        compatibilityScore: activeAssign?.compatibilityScore ?? '',
        qualityScore: lastEval ? Math.round(lastEval.qualityScore) : '',
        verdict: lastEval?.verdict || '',
        autoGenerated: t.autoGenerated,
        skillTags: (t.skillTags || []).join('|'),
      };
    });
    await logActivity(req.user.id, 'export.tasks_csv');
    sendCsv(res, 'tasks', ['id', 'title', 'status', 'priority', 'effortHours', 'deadline', 'assignedTo', 'compatibilityScore', 'qualityScore', 'verdict', 'autoGenerated', 'skillTags'], rows);
  } catch (e) { next(e); }
});

/** CSV export: workers with performance metrics. */
router.get('/workers.csv', auth, adminOnly, async (req, res, next) => {
  try {
    const workers = await prisma.worker.findMany({
      include: { user: { select: { name: true, email: true } }, skills: { include: { skill: true } } },
    });
    const rows = [];
    for (const w of workers) {
      const evals = await prisma.evaluation.findMany({ where: { submission: { workerId: w.id } } });
      const done = await prisma.task.count({ where: { status: 'COMPLETED', assignments: { some: { workerId: w.id, confirmedAt: { not: null } } } } });
      rows.push({
        id: w.id,
        name: w.user.name,
        email: w.user.email,
        seniorityTier: w.seniorityTier,
        baseCapacity: w.baseCapacity,
        effectiveCapacity: w.effectiveCapacity,
        scalingFactor: w.scalingFactor,
        availability: w.availability,
        skills: w.skills.map((s) => s.skill.name).join('|'),
        avgQuality: evals.length ? Math.round(evals.reduce((s, e) => s + e.qualityScore, 0) / evals.length) : '',
        onTimeRate: evals.length ? Math.round((evals.filter((e) => e.deadlineScore >= 60).length / evals.length) * 100) : '',
        completed: done,
      });
    }
    await logActivity(req.user.id, 'export.workers_csv');
    sendCsv(res, 'workers', ['id', 'name', 'email', 'seniorityTier', 'baseCapacity', 'effectiveCapacity', 'scalingFactor', 'availability', 'skills', 'avgQuality', 'onTimeRate', 'completed'], rows);
  } catch (e) { next(e); }
});

export default router;
