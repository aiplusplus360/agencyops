/**
 * Recurring task template engine.
 * Instantiates task templates on their configured cadence and routes
 * them into the assignment flow automatically.
 */
export async function instantiateDueTemplates() {
  const now = new Date();
  const instances = await prisma.recurringInstance.findMany({
    where: { status: 'PENDING', scheduledFor: { lte: now } },
    include: { template: true },
  });

  const created = [];
  for (const inst of instances) {
    const t = inst.template;
    const deadline = new Date(now.getTime() + t.effortHours * 3600 * 1000 * 2);
    try {
      const task = await prisma.task.create({
        data: {
          title: t.title,
          description: t.description,
          acceptanceCriteria: t.acceptanceCriteria || [],
          skillTags: t.skillTags || [],
          effortHours: t.effortHours,
          priority: 2,
          deadline,
          productId: t.productId,
          autoGenerated: true,
          status: 'PENDING',
        },
      });
      await prisma.recurringInstance.update({
        where: { id: inst.id },
        data: { status: 'GENERATED', taskId: task.id },
      });
      created.push(task);
    } catch (e) {
      console.error('template instantiation failed', e.message);
    }
  }
  return created;
}

/** Schedule next occurrence of a template based on cadence. */
export function nextOccurrence(cadence, from = new Date()) {
  const d = new Date(from);
  switch (cadence) {
    case 'DAILY': d.setDate(d.getDate() + 1); break;
    case 'WEEKLY': d.setDate(d.getDate() + 7); break;
    case 'MONTHLY': d.setMonth(d.getMonth() + 1); break;
    default: d.setDate(d.getDate() + 7);
  }
  return d;
}

export async function scheduleTemplate(template) {
  return prisma.recurringInstance.create({
    data: {
      templateId: template.id,
      scheduledFor: nextOccurrence(template.cadence),
    },
  });
}
