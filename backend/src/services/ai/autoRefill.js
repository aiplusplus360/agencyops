import prisma from '../../lib/prisma.js';
import { getSettings, recordAiDecision } from '../../lib/utils.js';
import { assignTask, computeCompatibility } from './matching.js';
import { chat, parseJson } from './client.js';
import { notifyWorker } from '../workerNotify.js';

/**
 * AI Auto-Refill Engine — keeps every worker's queue populated without admin prompts.
 * 1. Pull from the unassigned PENDING task pool (roadmap backlog).
 * 2. If empty, generate fresh tasks from the worker's skills + products (via LLM or fallback).
 * 3. Auto-assign the generated/pulled tasks.
 */
export async function refillWorker(workerId) {
  const settings = await getSettings();
  const policy = settings.autoRefill;

  const worker = await prisma.worker.findUnique({
    where: { id: workerId },
    include: {
      user: true,
      skills: { include: { skill: true } },
    },
  });
  if (!worker) return { workerId, refilled: 0 };
  if (worker.availability === 'ON_LEAVE' || worker.availability === 'AT_CAPACITY') {
    return { workerId, refilled: 0, skipped: 'availability' };
  }

  const activeCount = await prisma.assignment.count({
    where: { workerId, active: true, task: { status: { notIn: ['SUBMITTED', 'COMPLETED'] } } },
  });
  const effCap = worker.effectiveCapacity || worker.baseCapacity || 3;
  if (activeCount >= effCap) return { workerId, refilled: 0, skipped: 'at-capacity' };

  const target = Math.min(effCap, policy.minQueue + policy.batchSize);
  const slots = Math.max(0, target - activeCount);
  if (slots === 0) return { workerId, refilled: 0 };

  let tasks = await prisma.task.findMany({
    where: { status: 'PENDING', assignments: { none: { active: true } } },
    orderBy: [{ priority: 'asc' }, { deadline: 'asc' }],
    take: Math.max(slots * 3, 8),
  });

  // Route by best-fit: score candidates against this worker and keep the
  // highest-compatibility tasks so queues stay full with the right work.
  const scored = [];
  for (const t of tasks) {
    try {
      const { score } = await computeCompatibility(t, worker);
      scored.push({ task: t, score });
    } catch {
      scored.push({ task: t, score: 50 });
    }
  }
  scored.sort((a, b) => b.score - a.score);
  tasks = scored.slice(0, slots).map((s) => s.task);

  let generated = 0;
  if (tasks.length < slots) {
    generated = await generateTasksForWorker(worker, slots - tasks.length);
    const fresh = await prisma.task.findMany({
      where: {
        status: 'PENDING',
        autoGenerated: true,
        assignments: { none: { active: true } },
      },
      orderBy: { createdAt: 'desc' },
      take: slots - tasks.length,
    });
    tasks = [...tasks, ...fresh];
  }

  let refilled = 0;
  for (const task of tasks) {
    try {
      await assignTask(task.id, workerId, { assignedBy: 'AI', rationale: 'Auto-refill: worker queue below threshold.' });
      refilled++;
    } catch (e) {
      console.error('refill assign failed', e.message);
    }
  }

  if (refilled > 0) {
    await notifyWorker({
      userId: worker.userId,
      type: 'auto_refill',
      title: 'New tasks in your queue',
      body: `${refilled} task(s) were auto-assigned to you.`,
      socketEvent: 'queue_update',
    });
  }

  await recordAiDecision('AUTO_GENERATE', { workerId, refilled, generated, slots }, {
    entityId: workerId,
    rationale: 'Queue watchdog triggered auto-refill.',
  });

  return { workerId, refilled, generated };
}

async function generateTasksForWorker(worker, count) {
  const settings = await getSettings();
  const skillNames = worker.skills.map((ws) => ws.skill.name).join(', ') || 'general';
  const products = await prisma.product.findMany({ where: { active: true }, take: 2 });

  const content = await chat('autoRefill', [
    {
      role: 'system',
      content: `You are the AI-COO auto-refill engine for a marketing agency. Generate ${count} fresh, granular, client-ready marketing tasks for a team member whose queue is low. Return JSON:
{ "tasks": [ { "title": "...", "description": "...", "acceptanceCriteria": ["..."], "skillTags": ["..."], "effortHours": 3, "priority": 2 } ] }
Tasks should reflect agency work: content creation, social posts, ad creative, email flows, landing pages, SEO, reporting, competitor research, client deliverables.
IMPORTANT — task titles must NEVER contain an employee's name (no "Name:" prefixes, no "task for X"). Titles describe only the WORK itself.`,
    },
    {
      role: 'user',
      content: `Worker skills: ${skillNames}\nClients: ${products.map((p) => p.name).join(', ') || 'none'}\nGenerate ${count} tasks that keep this team member productively busy.`,
    },
  ], { temperature: 0.5, json: true }).catch(() => null);

  let generated = 0;
  if (content) {
    const parsed = parseJson(content);
    const tasks = parsed?.tasks || [];
    for (const t of tasks.slice(0, count)) {
      try {
        const deadline = new Date(Date.now() + (t.effortHours || 4) * 3600 * 1000 * 1.5);
        await prisma.task.create({
          data: {
            title: t.title,
            description: t.description,
            acceptanceCriteria: t.acceptanceCriteria || [],
            skillTags: t.skillTags || [],
            effortHours: t.effortHours || 4,
            priority: t.priority || 2,
            deadline,
            autoGenerated: true,
            status: 'PENDING',
          },
        });
        generated++;
      } catch (e) {
        console.error('generate task failed', e.message);
      }
    }
  }
  if (generated === 0) {
    // deterministic fallback
    const fallbackTitles = [
      'Draft a social post set for this week',
      'Write a short-form content piece for the blog',
      'Refresh ad creative variations for the active campaign',
      'Compile a competitor ad teardown',
    ];
    for (let i = 0; i < count; i++) {
      const deadline = new Date(Date.now() + 48 * 3600 * 1000);
      await prisma.task.create({
        data: {
          title: fallbackTitles[i % fallbackTitles.length],
          description: `Auto-generated agency task to keep the queue flowing (skills: ${skillNames}).`,
          acceptanceCriteria: ['Deliverable produced, on-brand and submitted'],
          skillTags: worker.skills.map((ws) => ws.skill.name),
          effortHours: 4,
          priority: 2,
          deadline,
          autoGenerated: true,
        },
      });
      generated++;
    }
  }
  return generated;
}

export async function refillAllWorkers() {
  const workers = await prisma.worker.findMany({ where: { user: { active: true } } });
  const results = [];
  for (const w of workers) {
    results.push(await refillWorker(w.id));
  }
  return results;
}
